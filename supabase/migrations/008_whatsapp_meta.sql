-- Nouvelles etapes de conversation (les deux etapes Twilio restent valides tant que l'ancien bot tourne)
do $$
declare c record;
begin
    for c in select conname from pg_constraint
             where conrelid = 'public.sessions_whatsapp'::regclass and contype = 'c' and pg_get_constraintdef(oid) ilike '%etape%'
    loop
        execute format('alter table public.sessions_whatsapp drop constraint %I', c.conname);
    end loop;
end $$;
alter table public.sessions_whatsapp add constraint sessions_whatsapp_etape_check check (etape in (
    'attente_photo', 'attente_localisation', 'attente_type', 'attente_description', 'confirmation',
    'attente_suivi', 'attente_proximite'
));

-- Idempotence (W3) et limite de debit par expediteur (S5). Le numero n'est jamais stocke en clair ici (S6).
