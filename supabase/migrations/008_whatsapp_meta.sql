alter table public.profils add column if not exists notifications_whatsapp boolean not null default false;

-- Signalements ouverts proches d'un point (5 km), pour « Obstructions près de moi »
create or replace function public.signalements_proches(p_lat double precision, p_lng double precision, p_limite integer default 5)
returns table (
    id uuid, numero_suivi bigint, type_obstruction text, statut text,
    commune text, quartier text, created_at timestamptz, distance_m double precision
)
language sql stable set search_path = ''
as $$
    select s.id, s.numero_suivi, s.type_obstruction, s.statut, s.commune, s.quartier, s.created_at,
           extensions.st_distance(
               s.localisation,
               extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography
           ) as distance_m
    from public.signalements s
    where s.statut in ('en_attente', 'verifie', 'en_cours')
      and extensions.st_dwithin(
          s.localisation,
          extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography,
          5000
      )
    order by distance_m
    limit least(greatest(p_limite, 1), 10);
$$;
revoke all on function public.signalements_proches(double precision, double precision, integer) from public, anon, authenticated;
grant execute on function public.signalements_proches(double precision, double precision, integer) to service_role;

-- D4 : l'auteur peut supprimer son signalement tant qu'il est en attente ; au-dela, seul un administrateur
create policy "Auteur supprime son signalement en attente" on public.signalements
    for delete to authenticated using ((select auth.uid()) = user_id and statut = 'en_attente');

-- Les 10 points gagnes au signalement sont repris : creer puis supprimer ne rapporte rien
do $$
declare c record;
begin
    for c in select conname from pg_constraint
             where conrelid = 'public.points_historique'::regclass and contype = 'c' and pg_get_constraintdef(oid) ilike '%raison%'
    loop
        execute format('alter table public.points_historique drop constraint %I', c.conname);
    end loop;
end $$;
alter table public.points_historique add constraint points_historique_raison_check check (raison in (
    'signalement', 'verification', 'signalement_verifie', 'signalement_resolu', 'badge', 'signalement_supprime'
));

create or replace function public.reprendre_points_signalement()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
    if old.user_id is not null and old.statut = 'en_attente' then
        perform public.attribuer_points(old.user_id, -10, 'signalement_supprime', null);
        update public.profils
           set nombre_signalements = greatest(nombre_signalements - 1, 0)
         where id = old.user_id;
    end if;
    return old;
end;
$$;
revoke all on function public.reprendre_points_signalement() from public, anon, authenticated;

drop trigger if exists reprendre_points_signalement on public.signalements;
create trigger reprendre_points_signalement
    before delete on public.signalements
    for each row execute function public.reprendre_points_signalement();
